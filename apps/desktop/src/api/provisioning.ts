export const PROVISIONING_STEPS = [
  "draft",
  "ssh_connecting",
  "host_key_pending",
  "authenticated",
  "discovering",
  "credential_stored",
  "kit_staged",
  "worker_installed",
  "enrollment_issued",
  "paired",
  "service_enabled",
  "heartbeat_seen",
  "smoke_check",
  "ready",
] as const;

export type ProvisioningStep = (typeof PROVISIONING_STEPS)[number];
export type ProvisioningState = ProvisioningStep | "failed";
export type ProvisioningIntent = "continue" | "resume" | "retry" | "rollback" | "remove";
export type ProvisioningAttention = "host_key" | "credential" | "external" | "intent" | null;
export type CredentialState = "pending" | "session_only" | "stored" | "forgotten";
export type SshAuthenticationMethod = "password" | "agent" | "private_key";
export type ServiceScope = "auto" | "user" | "system";
export type AllowedJobKind =
  | "build"
  | "test"
  | "static_analysis"
  | "compute"
  | "gpu"
  | "container"
  | "service"
  | "data_transform"
  | "media_transform"
  | "render";

export interface ProvisioningAdvancedOptions {
  serviceScope: ServiceScope;
  workspace?: string;
  priority: number;
  maximumParallelJobs?: number;
  cpuLimitPercent?: number;
  memoryLimitMiB?: number;
  allowedJobKinds: AllowedJobKind[];
  allowOnBattery: boolean;
}

export interface StartComputerInput {
  /** Stable for retries of one Add Computer submission; generated by the UI. */
  recordId: string;
  /** Stable worker identity paired with recordId for that submission. */
  intendedNodeId: string;
  displayName: string;
  host: string;
  port: number;
  username: string;
  authenticationMethod: SshAuthenticationMethod;
  /** Local controller path; validated natively and omitted unless private_key is selected. */
  privateKeyPath?: string;
  /** Request references are cleared after invocation; JavaScript cannot guarantee physical zeroization. Password auth only. */
  password: string;
  /** Request references are cleared after invocation; JavaScript cannot guarantee physical zeroization. Private-key auth only. */
  passphrase: string;
  rememberPassword: boolean;
  advanced: ProvisioningAdvancedOptions;
}

export interface ProvisioningActionInput {
  id: string;
  revision: number;
  /** Optional replacement for a lost, rejected, or stale SSH password; request references are cleared after invocation. */
  password?: string;
  /** Optional private-key passphrase retry; request references are cleared after invocation. */
  passphrase?: string;
}

export interface ProvisioningHostKey {
  algorithm: string;
  fingerprint: string;
  approved: boolean;
}

export interface ProvisioningFailure {
  code: string;
  retryable: boolean;
  /** Local fixed copy derived from the validated code; never controller-provided text. */
  message: string;
}

export interface ProvisioningInventory {
  hostname: string;
  operatingSystem: string;
  architecture: string;
  cpuModel: string;
  logicalCpuCount: number;
  memoryBytes: number;
  workspaceFreeBytes: number;
  gpuDevices: Array<{ name: string; memoryBytes?: number }>;
  toolchains: Record<string, string>;
}

export interface ProvisioningComputer {
  id: string;
  displayName: string;
  endpoint: { host: string; port: number; username: string };
  state: ProvisioningState;
  step: ProvisioningStep;
  attention: ProvisioningAttention;
  intent: ProvisioningIntent;
  revision: number;
  cycle: number;
  intendedNodeId: string;
  pairedNodeId?: string;
  hostKey?: ProvisioningHostKey;
  inventory?: ProvisioningInventory;
  credential: {
    authenticationMethod: SshAuthenticationMethod;
    rememberRequested: boolean;
    state: CredentialState;
  };
  configuration: ProvisioningAdvancedOptions;
  failure?: ProvisioningFailure;
  createdAt: string;
  updatedAt: string;
}

export interface ProvisioningOperationResult {
  outcome:
    | "checkpoint"
    | "awaiting_host_key_approval"
    | "awaiting_intent"
    | "awaiting_credential"
    | "awaiting_external"
    | "ready"
    | "failed"
    | "rolled_back"
    | "removed";
  computer?: ProvisioningComputer;
  removedId?: string;
}

export type ProvisioningUiAction =
  | "approve_host_key"
  | "continue"
  | "resume"
  | "retry"
  | "repair"
  | "rollback"
  | "remove"
  | "forget_ssh_password";

